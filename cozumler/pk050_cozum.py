"""
pk050 çözümü — String tekrar (*) gözlemi
"""

isim = input("İsmini gir: ")
print(isim * 3)

sayi = int(input("Bir sayı gir: "))
print(sayi * 3)

# Fark: isim * 3, ismi ekrana 3 kere yan yana yazdı (tekrar).
# sayi * 3 ise sayının 3 katını hesapladı (çarpma).
# Aynı * işareti, string'de tekrar, int'te çarpma anlamına geliyor.
